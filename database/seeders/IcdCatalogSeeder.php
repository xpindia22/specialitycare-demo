/**
 * Curated WHO ICD-10 catalog for diagnosis autocomplete on the encounter form.
 *
 * ~1,000 codes covering every chapter with depth in cardiology, diabetes,
 * respiratory, digestive, MSK, paeds, and the health-services (Z) chapter —
 * tuned for an Indian general + cardiology clinic. Idempotent: codes are
 * upserted by `code`, so re-running is safe and existing rows in icd_codes
 * are preserved/updated rather than duplicated.
 *
 * Doctors can add more via the admin lookup or extend this file. Subcodes use
 * the WHO dot notation (e.g. I25.10 — atherosclerotic heart disease).
 */
class IcdCatalogSeeder extends Seeder
{
    public function run(): void
    {
        $rows = [];
        foreach ($this->catalog() as $cat => $codes) {
            foreach ($codes as $code => $desc) {
                $rows[] = ['code' => $code, 'description' => $desc, 'category' => $cat];
            }
        }
        DB::table('icd_codes')->upsert(
            array_map(fn ($r) => $r + ['updated_at' => now(), 'created_at' => now()], $rows),
            ['code'],
            ['description', 'category', 'updated_at'],
        );
        $this->command->info("Upserted {$this->countRows($rows)} ICD-10 codes across " . count($this->catalog()) . " chapters.");
    }

    private function countRows(array $rows): int { return count($rows); }

